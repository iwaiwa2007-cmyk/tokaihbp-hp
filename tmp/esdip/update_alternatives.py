from pathlib import Path
root=Path('outputs/十二指腸ESDIP申請案')
p=root/'01_説明同意書案.txt'
s=p.read_text()
new='''6　代わりに選べる治療と治療しない場合
治療の選択肢には、以下の方法があります。どの方法が適しているかは、腫瘍の大きさ・広がり、がんの有無や深さ、胆管・膵管への進展、全身状態、ご本人の希望によって異なります。すべての方法が今回の病変に適用できるわけではありません。

（1）通常の内視鏡的乳頭切除術と、必要に応じた周囲病変の内視鏡切除
口から内視鏡を入れ、輪状の器具（スネア）で乳頭部の腫瘍を切除する方法です。周囲に広がる病変には、内視鏡的粘膜切除術（EMR）などを組み合わせることがあります。お腹を切らずに治療できますが、病変が大きい場合や広く進展している場合は、複数に分けて切除する必要があります。その場合、切除した端に腫瘍が残っていないかの病理評価が難しくなることがあります。腫瘍の遺残・再発によって追加治療が必要になる場合があり、治療後も定期的な検査が必要です。出血、穿孔、膵炎、胆管炎などの合併症が起こる可能性があります。

（2）外科手術による膵頭十二指腸切除術
膵臓の頭側の部分、十二指腸、胆管の一部などを切除し、消化管と胆汁・膵液の通り道をつなぎ直す手術です。必要な範囲のリンパ節も切除できます。浸潤がんやリンパ節転移の可能性がある場合、胆管・膵管内への広がりなどにより内視鏡では十分に切除できない場合に検討します。内視鏡治療より広い範囲を切除できる一方、身体への負担が大きく、膵液や胆汁の漏れ、出血、感染などの合併症が起こることがあります。回復に時間を要し、消化吸収や血糖の管理に治療が必要となる場合もあります。ESDIP後の病理結果によって、この手術を追加で勧めることもあります。

（3）外科的な局所切除術
病変の性質や広がりによっては、外科手術で乳頭部と周囲の病変を限局して切除する方法を検討することがあります。膵臓を温存できる可能性がありますが、出血、膵液・胆汁の漏れ、感染、胆管・膵管の出口の狭窄などのリスクがあります。広範囲の病変や、リンパ節への転移が問題となるがんには十分な治療とならない場合があります。切除後も経過観察が必要で、病理結果や遺残・再発によって膵頭十二指腸切除術などの追加治療が必要になることがあります。今回の病変に可能かどうかは外科医と検討します。

（4）切除せずに経過を観察する方法
全身状態や治療に伴う危険性、ご本人の希望などを踏まえて、直ちに切除せず、内視鏡検査などで経過を観察する選択肢もあります。切除に伴う合併症を当面避けられますが、腫瘍を取り除く治療ではありません。観察中に腫瘍が大きくなる、腺腫ががんになる、すでにあるがんが進行する、出血・黄疸・膵炎などを生じる可能性があります。後に内視鏡での治療が難しくなる場合もあります。変化が起こる時期や程度は一律には予測できず、定期的な検査をしても進行を必ず防げるわけではありません。

今回の患者さんについての比較と治療選択
病変の診断・大きさ・広がり：［要記入］
通常の内視鏡的乳頭切除が適するか、一括切除が可能か：［要記入］
外科手術の適応と、全身状態からみた負担：［要記入］
経過観察を選ぶ場合の見込みと検査計画：［要記入］
これらと比較してESDIPを提案する理由：［患者さん固有の検査所見と検討結果に基づき記入］
ご本人の希望：［要記入］
他院での治療やセカンドオピニオンをご希望の場合は、ご相談ください。

'''
a=s.index('6　代わりに'); b=s.index('7　治療前後',a)
assert '通常の内視鏡的乳頭切除' in s[a:b]
p.write_text(s[:a]+new+s[b:])
(root/'04_代替治療の説明文.txt').write_text(new+'参考資料（医療者向け）\n内視鏡的乳頭切除術診療ガイドライン2021：\nhttps://www.jstage.jst.go.jp/article/gee/63/4/63_451/_html/-char/ja\nESGE乳頭部腫瘍ガイドライン2021：\nhttps://www.esge.com/assets/downloads/pdfs/guidelines/2021_a_1397_3198.pdf\n一般的な選択肢の説明案。患者固有の適応は未確定。非乳頭部病変のESDの推奨をESDIPの推奨に置き換えていない。\n')
assert p.read_text().count('7　治療前後')==1
print('説明同意書の第6項を更新し、代替治療の説明文も個別保存しました。')
